CREATE TABLE app_user (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    email    VARCHAR(255),
    role     VARCHAR(50) NOT NULL DEFAULT 'ROLE_USER',
    CONSTRAINT uk_app_user_username UNIQUE (username)
);

CREATE TABLE book (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title    VARCHAR(255) NOT NULL,
    author   VARCHAR(255) NOT NULL,
    price    DECIMAL(19, 4) NOT NULL,
    category VARCHAR(255),
    stock    INTEGER NOT NULL,
    version  BIGINT
);

CREATE TABLE cart (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE
);

CREATE TABLE cart_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id      BIGINT NOT NULL,
    cart_id      BIGINT,
    quantity     INTEGER NOT NULL,
    price_at_add DECIMAL(19, 4) NOT NULL,
    added_at     TIMESTAMP NOT NULL,
    CONSTRAINT fk_cart_items_book FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES cart(id) ON DELETE CASCADE
);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    total_price DECIMAL(19, 4) NOT NULL,
    status      VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    version     BIGINT,
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE
);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT NOT NULL,
    order_id   BIGINT NOT NULL,
    quantity   INTEGER NOT NULL,
    unit_price DECIMAL(19, 4) NOT NULL,
    subtotal   DECIMAL(19, 4) NOT NULL,
    CONSTRAINT fk_order_items_book FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);
