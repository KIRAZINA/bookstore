CREATE TABLE inventory (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id            BIGINT NOT NULL,
    available_quantity INTEGER NOT NULL DEFAULT 0,
    reserved_quantity  INTEGER NOT NULL DEFAULT 0,
    last_updated       TIMESTAMP NOT NULL DEFAULT NOW(),
    version            BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_inventory_book FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE CASCADE,
    CONSTRAINT chk_inventory_available_non_negative CHECK (available_quantity >= 0),
    CONSTRAINT chk_inventory_reserved_non_negative CHECK (reserved_quantity >= 0),
    CONSTRAINT uq_inventory_book_id UNIQUE (book_id)
);

CREATE INDEX idx_inventory_book_id ON inventory(book_id);

INSERT INTO inventory (book_id, available_quantity, reserved_quantity, version)
SELECT id, stock, 0, 1 FROM book;

-- book.stock is DEPRECATED. The inventory table is the source of truth for availability.
-- book.stock will be removed in a future migration after all consumers migrate to inventory.

CREATE TABLE inventory_history (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id       BIGINT NOT NULL,
    book_id            BIGINT NOT NULL,
    event_type         VARCHAR(20) NOT NULL,
    previous_available INTEGER,
    new_available      INTEGER,
    previous_reserved  INTEGER,
    new_reserved       INTEGER,
    quantity_change    INTEGER NOT NULL,
    order_id           BIGINT,
    payment_id         BIGINT,
    changed_by         VARCHAR(255),
    reason             VARCHAR(500),
    created_at         TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_inventory_history_inventory FOREIGN KEY (inventory_id) REFERENCES inventory(id) ON DELETE CASCADE,
    CONSTRAINT fk_inventory_history_book FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE CASCADE
);

CREATE INDEX idx_inventory_history_inventory_id ON inventory_history(inventory_id);
CREATE INDEX idx_inventory_history_book_id ON inventory_history(book_id);
CREATE INDEX idx_inventory_history_order_id ON inventory_history(order_id);
CREATE INDEX idx_inventory_history_event_type ON inventory_history(event_type);
CREATE INDEX idx_inventory_history_created_at ON inventory_history(created_at);
